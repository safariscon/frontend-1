// Get translation by key
export function t(key, locale = defaultLanguage, params = {}) {
  const safeLocale = isSupportedLanguage(locale) ? locale : defaultLanguage;
  const keys = key.split('.');
  let value = translations[safeLocale];
  
  for (const k of keys) {
    value = value?.[k];
  }
  
  if (!value) {
    // Fallback to English
    value = translations[defaultLanguage];
    for (const k of keys) {
      value = value?.[k];
    }
  }
  
  // Replace parameters
  if (typeof value === 'string') {
    Object.keys(params).forEach((param) => {
      value = value.replace(`{${param}}`, params[param]);
    });
  }
  
  return value || key;
}
